        val handlerJs = """
import config from './config.js';
import { commands } from './commands.js';

export async function messageHandler(sock, m) {
  if (!m.message) return;
  const from = m.key.remoteJid;
  const isGroup = from.endsWith('@g.us');
  const body = m.message.conversation || m.message.extendedTextMessage?.text || '';
  
  if (!body.startsWith(config.prefix)) return;
  
  const args = body.slice(config.prefix.length).trim().split(/ +/);
  const commandName = args.shift().toLowerCase();
  
  if (config.maintenanceMode && !m.key.fromMe) {
    return sock.sendMessage(from, { text: '⚠️ [SYSTEM] Bot sedang dalam mode perawatan (maintenance).' });
  }

  if (commandName === 'menu' || commandName === 'help') {
    let menuText = `╭━━━━━━❰ ${cfg.botName} ❱━━━━━━╮\n`;
    menuText += `┃ 👑 Owner: ${cfg.ownerName}\n`;
    menuText += `┃ ⚡ Prefix: [ ${cfg.prefix} ]\n`;
    menuText += `┃ 🛠 Style: ${cfg.menuStyle}\n`;
    menuText += `┃ 🚀 Total Fitur Aktif: ${activeFeatures.size}\n`;
    menuText += `╰━━━━━━━━━━━━━━━━━━━━━━━━╯\n\n`;
    
    let currentCat = '';
    for (const [cmd, data] of commands.entries()) {
      if (data.category !== currentCat) {
        currentCat = data.category;
        menuText += `\n╭─「 📁 *${'$'}{currentCat}* 」\n`;
      }
      menuText += `│ 🔹 ${cfg.prefix}${'$'}{cmd} (${'$'}{data.name})\n`;
    }
    menuText += `╰─────────────────────\n\n_BGR PRJCT BOT GENERATOR by ARDZYN_`;
    return sock.sendMessage(from, { text: menuText }, { quoted: m });
  }

  const cmd = commands.get(commandName);
  if (cmd) {
    try {
      await cmd.execute(sock, m, args);
    } catch (err) {
      console.error('Command Execution Error:', err);
      await sock.sendMessage(from, { text: '❌ Terjadi kesalahan saat memproses perintah.' });
    }
  } else {
    if (config.autoReply) {
      await sock.sendMessage(from, { 
        text: `Command "${'$'}{commandName}" tidak ditemukan. Ketik ${cfg.prefix}menu untuk melihat daftar fitur.` 
      });
    }
  }
}
""".trimIndent()

        val indexJs = """
import { makeWASocket, useMultiFileAuthState, DisconnectReason } from '@whiskeysockets/baileys';
import pino from 'pino';
import config from './config.js';
import { messageHandler } from './handler.js';

async function startBot() {
  console.log(`🌌 Starting ${cfg.botName} by ${cfg.ownerName} [BGR PRJCT]...`);
  
  const { state, saveCreds } = await useMultiFileAuthState('./session_auth');
  
  const sock = makeWASocket({
    logger: pino({ level: 'silent' }),
    printQRInTerminal: true,
    auth: state,
    browser: ['BOT GENERATOR', 'Chrome', '1.0.0']
  });

  sock.ev.on('creds.update', saveCreds);

  sock.ev.on('connection.update', (update) => {
    const { connection, lastDisconnect, qr } = update;
    if (qr) {
      console.log('⚡ Scan QR Code di atas dengan aplikasi WhatsApp Anda.');
    }
    if (connection === 'close') {
      const shouldReconnect = (lastDisconnect.error)?.output?.statusCode !== DisconnectReason.loggedOut;
      console.log('Koneksi terputus. Menghubungkan kembali:', shouldReconnect);
      if (shouldReconnect) startBot();
    } else if (connection === 'open') {
      console.log('✅ Bot WhatsApp terhubung dengan sukses!');
    }
  });

  sock.ev.on('messages.upsert', async ({ messages }) => {
    const m = messages[0];
    if (!m) return;
    await messageHandler(sock, m);
  });
}

startBot();
""".trimIndent()

