        val botJs = """
const { Telegraf, Markup } = require('telegraf');
require('dotenv').config();

const bot = new Telegraf(process.env.BOT_TOKEN || 'YOUR_TELEGRAM_BOT_TOKEN');

bot.start((ctx) => {
  ctx.reply(
    `🪐 *Selamat Datang di ${cfg.botName}!* \n\n${cfg.welcomeMessage}\n\nOwner: *${cfg.ownerName}*\nTotal Modul Aktif: *${activeFeatures.size}*`,
    {
      parse_mode: 'Markdown',
      ...Markup.inlineKeyboard([
        [Markup.button.callback('📜 Menu Utama', 'btn_menu')],
        [Markup.button.callback('⚡ Info Sistem', 'btn_info')]
      ])
    }
  );
});

bot.help((ctx) => {
  ctx.reply(`Gunakan prefix ${cfg.prefix} atau tombol menu untuk melihat seluruh perintah.`);
});

bot.action('btn_menu', (ctx) => {
  ctx.reply('╭━━━❰ DAFTAR FITUR TELEGRAM ❱━━━╮\n/start - Mulai bot\n/help - Bantuan\n/ping - Cek latensi\n/status - Status server\n╰━━━━━━━━━━━━━━━━━━━━━━╯');
