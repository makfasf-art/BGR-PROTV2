        val indexJs = """
const { Client, GatewayIntentBits, EmbedBuilder, ActivityType } = require('discord.js');
require('dotenv').config();
const config = require('./config.json');

const client = new Client({
  intents: [
    GatewayIntentBits.Guilds,
    GatewayIntentBits.GuildMessages,
    GatewayIntentBits.MessageContent,
    GatewayIntentBits.GuildMembers
  ]
});

client.once('ready', () => {
  console.log(`🌌 Discord Bot Logged in as ${'$'}{client.user.tag}`);
  console.log(`⚡ Engineered by ${cfg.ownerName} [BGR PRJCT]`);
  client.user.setActivity(`${cfg.prefix}help | BGR PRJCT`, { type: ActivityType.Playing });
});

client.on('messageCreate', async (message) => {
  if (message.author.bot) return;
  if (!message.content.startsWith(cfg.prefix)) return;

  const args = message.content.slice(cfg.prefix.length).trim().split(/ +/);
  const command = args.shift().toLowerCase();

  if (command === 'help' || command === 'menu') {
    const embed = new EmbedBuilder()
      .setColor('#8B5CF6')
      .setTitle(`🪐 ${cfg.botName} - Command Dashboard`)
      .setDescription(`Welcome to the control center! Prefix: \`${cfg.prefix}\``)
      .addFields(
        { name: '👑 Creator', value: "${cfg.ownerName}", inline: true },
        { name: '🛠 Active Features', value: `${activeFeatures.size} Modules`, inline: true },
        { name: '🎨 Theme', value: "${cfg.theme}", inline: true }
      )
      .setFooter({ text: 'BGR PRJCT BOT GENERATOR by ARDZYN' })
      .setTimestamp();
    return message.reply({ embeds: [embed] });
  }

  if (command === 'ping') {
    return message.reply(`🏓 Pong! Latency: ${'$'}{client.ws.ping}ms`);
  }
});

client.login(process.env.DISCORD_TOKEN || 'YOUR_BOT_TOKEN_HERE');
""".trimIndent()

        val deployJs = """
const { REST, Routes, SlashCommandBuilder } = require('discord.js');
require('dotenv').config();

const commands = [
  new SlashCommandBuilder().setName('help').setDescription('Open bot menu dashboard'),
  new SlashCommandBuilder().setName('ping').setDescription('Check bot ping response'),
