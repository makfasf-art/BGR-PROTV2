        val activeFeatures = project.features.filter { it.isEnabled }
        val cfg = project.config

        val packageJson = """
{
  "name": "${cfg.botName.lowercase().replace(" ", "-")}",
  "version": "1.0.0",
  "description": "WhatsApp Multi-Device Bot generated by BGR PRJCT (BOT GENERATOR)",
  "main": "index.js",
  "type": "module",
  "scripts": {
    "start": "node index.js",
    "dev": "nodemon index.js"
  },
  "keywords": ["whatsapp-bot", "baileys", "bgr-prjct", "bot-generator"],
  "author": "${cfg.ownerName}",
  "license": "MIT",
  "dependencies": {
    "@whiskeysockets/baileys": "^6.7.0",
    "pino": "^9.0.0",
    "qrcode-terminal": "^0.12.0",
    "chalk": "^5.3.0",
    "dotenv": "^16.4.5"
  }
}
""".trimIndent()

        val configJs = """
// ==========================================
// BGR PRJCT - BOT GENERATOR CONFIGURATION
// Generated for WhatsApp Multi-Device (Baileys)
// ==========================================

export default {
  botName: "${cfg.botName}",
  botUsername: "${cfg.botUsername}",
