package com.example.generator

import com.example.data.model.BotPlatform
import com.example.data.model.BotProject

data class GeneratedFile(
    val fileName: String,
    val path: String,
    val language: String,
    val content: String
)

object BotCodeGenerator {

    fun generateProjectFiles(project: BotProject): List<GeneratedFile> {
        return when (project.platform) {
            BotPlatform.WHATSAPP -> generateWhatsAppProject(project)
            BotPlatform.DISCORD -> generateDiscordProject(project)
            BotPlatform.TELEGRAM -> generateTelegramProject(project)
        }
    }

