        val commandsCode = StringBuilder()
        commandsCode.append("// Active Commands Handler\n")
        commandsCode.append("export const commands = new Map();\n\n")

        activeFeatures.take(60).forEach { feat ->
            commandsCode.append("""
commands.set("${feat.command}", {
  name: "${feat.name}",
  category: "${feat.category.name}",
  permission: "${feat.permission.name}",
